"""Concept "sort": ball-sort puzzle solved in 3D - candy balls hop from glass tube to glass tube until every
tube holds one colour. Pop on each lift, rising clinks on each landing, sparkle + note when a tube is complete.
python3 c_sort.py <out_dir> [seed] [res] [samples]   env: COLORS=4  MOVES=16  BG
The scramble is generated by random legal *reverse* moves from the solved state, so the replay is always valid.
"""
import sys, os, math, random
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bpy, bmesh
from common import *

out = sys.argv[1]
seed = int(sys.argv[2]) if len(sys.argv) > 2 else 1
res = float(sys.argv[3]) if len(sys.argv) > 3 else 0.4
spp = int(sys.argv[4]) if len(sys.argv) > 4 else 10
random.seed(seed)
NC = int(os.environ.get("COLORS", 4))
CAP = 4
NT = NC + 2
NMOVES = int(os.environ.get("MOVES", random.choice([16, 18, 20])))
BG = os.environ.get("BG", pick_bg())

# ---- puzzle: scramble backwards from solved ----
solved = [[c] * CAP for c in range(NC)] + [[] for _ in range(NT - NC)]
state = [t[:] for t in solved]
moves = []          # forward moves (a -> b), stored reversed later
last = None
tries = 0
while len(moves) < NMOVES and tries < 20000:
    tries += 1
    b = random.randrange(NT)
    if not state[b]:
        continue
    x = state[b][-1]
    rest = state[b][:-1]
    if rest and rest[-1] != x:
        continue
    a = random.randrange(NT)
    if a == b or len(state[a]) >= CAP:
        continue
    if last == (b, a):          # don't immediately undo
        continue
    state[b].pop(); state[a].append(x)
    moves.append((a, b))        # forward: from a back to b
    last = (a, b)
start = [t[:] for t in state]
moves.reverse()
print("moves", len(moves), "start", start, flush=True)

# ---- timing ----
LEAD = 20
LIFT, OVER, DROP, GAP = 6, 7, 6, 2
MOVE = LIFT + OVER + DROP + GAP
nframes = LEAD + len(moves) * MOVE + 50
scn = reset(nframes, seed)
studio(BG)

R = 0.16
TR_IN, TR_OUT = R + 0.025, R + 0.045
SP = 0.58
TH = CAP * 2 * R + 0.22        # tube height
NFRONT = (NT + 1) // 2
SHELF_Y, SHELF_Z = 1.0, 2.15  # back row stands on a shelf behind and above the front row
pos = []
for i in range(NT):
    row = 0 if i < NFRONT else 1
    n = NFRONT if row == 0 else NT - NFRONT
    j = i if row == 0 else i - NFRONT
    pos.append(((j - (n - 1) / 2) * SP, SHELF_Y * row, 0.12 + SHELF_Z * row))


def zslot(t, k):               # ball centre for stack position k of tube t
    return pos[t][2] + 0.05 + R + k * 2 * R


def topz(t):
    return pos[t][2] + TH + R + 0.1


white = plastic("plate", (0.98, 0.98, 1.0), rough=0.25, coat=0.6)
pl = box("plate", SP * NFRONT + 0.3, 0.75, 0.12, (0, 0, 0.06)); bevel(pl, 0.04, 4); set_mat(pl, white)
sh = box("shelf", SP * NFRONT + 0.3, 0.75, SHELF_Z + 0.12, (0, SHELF_Y, (SHELF_Z + 0.12) / 2)); bevel(sh, 0.04, 4); set_mat(sh, white)
# "display glass": transparent + fresnel gloss (no refraction darkening, light reaches the balls inside)
gl = bpy.data.materials.new("tubeglass"); gl.use_nodes = True
nt = gl.node_tree; nt.nodes.clear()
o = nt.nodes.new("ShaderNodeOutputMaterial"); mx = nt.nodes.new("ShaderNodeMixShader")
tr = nt.nodes.new("ShaderNodeBsdfTransparent"); tr.inputs["Color"].default_value = (0.93, 0.97, 1.0, 1)
gs = nt.nodes.new("ShaderNodeBsdfGlossy"); gs.inputs["Roughness"].default_value = 0.04
fr = nt.nodes.new("ShaderNodeLayerWeight"); fr.inputs["Blend"].default_value = 0.12
ad = nt.nodes.new("ShaderNodeMath"); ad.operation = "MULTIPLY_ADD"; ad.inputs[1].default_value = 0.3; ad.inputs[2].default_value = 0.02; ad.use_clamp = True
nt.links.new(fr.outputs["Fresnel"], ad.inputs[0]); nt.links.new(ad.outputs[0], mx.inputs[0])
nt.links.new(tr.outputs[0], mx.inputs[1]); nt.links.new(gs.outputs[0], mx.inputs[2]); nt.links.new(mx.outputs[0], o.inputs["Surface"])
for i, (x, y, z) in enumerate(pos):
    def cyl(bm):
        bmesh.ops.create_cone(bm, cap_ends=True, segments=48, radius1=TR_OUT, radius2=TR_OUT, depth=TH)
        top = [f for f in bm.faces if f.normal.z > 0.5]
        bmesh.ops.delete(bm, geom=top, context="FACES")
    t = mesh_from_bm(f"tube{i}", cyl)
    t.location = (x, y, z + TH / 2)
    so = t.modifiers.new("s", "SOLIDIFY"); so.thickness = TR_OUT - TR_IN; so.offset = -1
    for p in t.data.polygons:
        p.use_smooth = True
    apply_mods(t)
    set_mat(t, gl)
    t.visible_glossy = False      # no glass-in-glass reflection loops (they go black at low bounce counts)
    t.visible_shadow = False

off = random.randrange(len(RAINBOW))
cols = [RAINBOW[(off + (i * len(RAINBOW)) // NC) % len(RAINBOW)] for i in range(NC)]   # well-separated hues
mats = [plastic(f"ball{c}", cols[c], rough=0.16, coat=0.9) for c in range(NC)]

balls = [[] for _ in range(NT)]   # object stacks
for ti, stack in enumerate(start):
    for k, c in enumerate(stack):
        def sb(bm):
            bmesh.ops.create_uvsphere(bm, u_segments=36, v_segments=20, radius=R)
        b = mesh_from_bm(f"b{ti}_{k}", sb)
        for p in b.data.polygons:
            p.use_smooth = True
        set_mat(b, mats[c])
        b.location = (pos[ti][0], pos[ti][1], zslot(ti, k))
        b["col"] = c
        key_loc(b, 1, b.location[:])
        balls[ti].append(b)

events = [[LEAD - 8, "whoosh_short", 0.4]]
cstate = [t[:] for t in start]
done_tubes = set()
f = LEAD
for mi, (a, b) in enumerate(moves):
    ob = balls[a].pop()
    za = zslot(a, len(balls[a]))
    zb = zslot(b, len(balls[b]))
    xa, ya, _ = pos[a]; xb, yb, _ = pos[b]
    ta, tb = topz(a), topz(b)
    key_loc(ob, f, (xa, ya, za))
    for k in range(1, LIFT + 1):
        e = 1 - (1 - k / LIFT) ** 2
        key_loc(ob, f + k, (xa, ya, za + (ta - za) * e))
    for k in range(1, OVER + 1):
        u = k / OVER
        e = u * u * (3 - 2 * u)
        key_loc(ob, f + LIFT + k, (xa + (xb - xa) * e, ya + (yb - ya) * e, ta + (tb - ta) * e + 0.25 * math.sin(math.pi * u)))
    f0 = f + LIFT + OVER
    for k in range(1, DROP + 1):
        u = k / DROP
        key_loc(ob, f0 + k, (xb, yb, tb + (zb - tb) * u * u))
    key_loc(ob, f0 + DROP + 1, (xb, yb, zb + 0.03))
    key_loc(ob, f0 + DROP + 2, (xb, yb, zb))
    balls[b].append(ob)
    c = cstate[a].pop(); cstate[b].append(c)
    pan = max(-0.8, min(0.8, xb / SP / 2))
    events.append([f + 1, "pop", 0.55, None, max(-0.8, min(0.8, xa / SP / 2))])
    events.append([f0 + DROP, "clink", 0.8, len(cstate[b]) - 1, pan])
    events.append([f0 + DROP, "thock", 0.35, len(cstate[b]) - 1, pan])
    if len(cstate[b]) == CAP and len(set(cstate[b])) == 1 and b not in done_tubes:
        done_tubes.add(b)
        events.append([f0 + DROP + 1, "sparkle", 0.7])
        events.append([f0 + DROP + 1, "pluck", 0.6, 2 + 2 * len(done_tubes)])
    f += MOVE
for row in balls:
    for ob in row:
        set_interp(ob, "LINEAR")
events.append([f + 2, "chord", 1.0])
assert all(len(t) in (0, CAP) and len(set(t)) <= 1 for t in cstate), cstate
# None pitch step -> drop field
events = [[e[0], e[1], e[2], 0, e[4]] if len(e) > 3 and e[3] is None else e for e in events]

os.environ.setdefault("TBOUNCES", "8")
camera((0.0, -7.0, 3.4), (0, 0.5, 2.05), lens=float(os.environ.get("LENS", 46)))
caption = random.choice(["Sorted in %d moves" % len(moves), "Ball sort, but satisfying", "Every colour home", "Wait for the last tube"])
finish(out, events, nframes, res, spp, static_until=LEAD,
       meta={"concept": "sort", "colors": NC, "moves": len(moves), "bg": BG, "caption": caption})
